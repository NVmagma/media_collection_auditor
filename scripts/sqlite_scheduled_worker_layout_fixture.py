"""Real HTTP + actual routed renames with separate disposable control/media."""
from datetime import timedelta
import json
import sys
import unittest
from unittest.mock import patch

from app.sqlite_operation_coordinator import INTENTS_KEY
from app.sqlite_scheduled_worker_layout import run_disposable_worker_layout
from app.state_store import GuardedSQLiteStateStore
from scripts.sqlite_scheduled_configured_slot_fixture import ConfiguredSlotFixtureTests, NOW


@unittest.skipUnless(sys.platform == 'linux', 'Actual no-replace rename requires Linux')
class WorkerLayoutFixtureTests(unittest.TestCase):
    def setUp(self):
        self.case = ConfiguredSlotFixtureTests(); self.case.setUp()
        self.addCleanup(self.case.doCleanups)
        self.root = self.case.fixture.root
        self.control = self.root / 'control'; self.control.mkdir()
        (self.control / '.sqlite_disposable_rehearsal').write_text('DISPOSABLE ONLY\n')
        (self.root / 'state.db').rename(self.control / 'state.db')
        self.store = GuardedSQLiteStateStore(self.control / 'state.db')
        self.before = self.store.load_with_revision()

    def run_slot(self, **kwargs):
        return run_disposable_worker_layout(lab_root=self.root,
            control_root=kwargs.pop('control_root', self.control),
            settings=kwargs.pop('settings', self.case.values), scheduled_at=self.case.fixture.slot,
            now=self.case.fixture.slot + timedelta(seconds=1), clock=lambda: NOW, **kwargs)

    def claims(self):
        return list((self.control / '.sqlite_scheduled_slots').glob('*.json'))

    def test_separate_database_routes_both_libraries_without_outer_state(self):
        result = self.run_slot()
        self.assertEqual(result['layout'], 'separate_control_and_media')
        self.assertEqual(len(result['completed']), 2)
        self.assertEqual(self.store.load_with_revision()[1], self.before[1] + 6)
        self.assertFalse((self.root / 'state.db').exists())
        self.assertEqual(len(self.claims()), 1)
        with self.assertRaises(FileExistsError):
            self.run_slot()
        self.assertEqual(len(self.case.server.calls), 7)

    def test_pending_operation_blocks_collection_in_separate_database(self):
        state, revision = self.before
        # A valid retained intent generated by a real rename is tested below;
        # mere presence must also fail before any remote collection.
        state[INTENTS_KEY] = {}
        self.store.save_if_revision(state, revision)
        with self.assertRaises(Exception):
            self.run_slot()
        self.assertEqual(self.case.server.calls, [])
        self.assertEqual(len(self.claims()), 1)

    def test_control_database_replacement_during_http_is_not_adopted(self):
        def replace_database():
            self.case.server.on_request = None
            database = self.control / 'state.db'
            payload = database.read_bytes()
            database.rename(self.control / 'original.db')
            database.write_bytes(payload)
        self.case.server.on_request = replace_database
        with self.assertRaises(RuntimeError):
            self.run_slot()
        self.assertEqual(self.store.load_with_revision(), self.before)
        self.assertTrue(all(self.case.fixture.fixture.path(i, 'transient').is_dir() for i in (0, 1)))

    def test_control_lock_stays_held_during_real_collection(self):
        from app.sqlite_isolated_lifecycle_runner import isolated_runner_lock
        observed = []
        def competing_runner():
            with self.assertRaisesRegex(RuntimeError, 'Another isolated'):
                with isolated_runner_lock(self.control):
                    self.fail('Lock bypass')
            observed.append(True)
        self.case.server.on_request = competing_runner
        self.assertEqual(len(self.run_slot()['completed']), 2)
        self.assertEqual(len(observed), 7)

    def test_missing_outer_marker_rejects_before_any_claim_or_http(self):
        (self.root / '.sqlite_disposable_rehearsal').unlink()
        with self.assertRaises(FileNotFoundError):
            self.run_slot()
        self.assertFalse(self.claims())
        self.assertEqual(self.case.server.calls, [])

    def test_media_overlap_with_control_and_outside_control_are_rejected(self):
        values = dict(self.case.values)
        values['RADARR_KEEP_PATH'] = str(self.control / 'media')
        with self.assertRaises(ValueError):
            self.run_slot(settings=values)
        with self.assertRaises(ValueError):
            self.run_slot(control_root=self.root.parent)
        self.assertFalse(self.claims())
        self.assertEqual(self.case.server.calls, [])

    def test_failure_after_rename_retains_intent_in_control_database(self):
        import app.sqlite_scheduled_routed_batch as batch
        rename = batch.rename_directory_noreplace_at
        def fail_after(*args):
            rename(*args)
            raise RuntimeError('fixture lost rename acknowledgement')
        with patch.object(batch, 'rename_directory_noreplace_at', fail_after):
            result = self.run_slot()
        self.assertEqual(result['status'], 'stopped')
        state, revision = self.store.load_with_revision()
        self.assertIn(INTENTS_KEY, state)
        self.assertEqual(revision, self.before[1] + 1)
        self.assertTrue(self.case.fixture.fixture.path(0, 'holding').is_dir())
        self.assertTrue(self.case.fixture.fixture.path(1, 'transient').is_dir())
        self.assertEqual(len(self.claims()), 1)

    def test_invalid_run_deadline_does_not_create_claim(self):
        with self.assertRaises(ValueError):
            self.run_slot(maximum_run_seconds=0)
        self.assertFalse(self.claims())
        self.assertEqual(self.case.server.calls, [])


if __name__ == '__main__':
    result = unittest.TextTestRunner(verbosity=2).run(
        unittest.defaultTestLoader.loadTestsFromTestCase(WorkerLayoutFixtureTests))
    if not result.wasSuccessful() or result.testsRun != 8 or result.skipped:
        raise SystemExit(1)
    print(json.dumps({'status': 'scheduled_worker_layout_verified', 'tests': result.testsRun,
        'fixture_only': True, 'production_authorized': False, 'production_activation': 'disabled'}))
